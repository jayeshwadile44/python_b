print(name[0:3])  # prints the first three characters of the string
print(name[1])  # prints the second character of the string
print(name[2])  # prints the third character of the string
print(name[5])  # prints the fifth character of the string

print(name[-1])  # prints the last character of the string
print(name[-2])  # prints the second last character of the string
print(name[-3])  # prints the third last character of the string
print(name[-6])  # prints the sixth last character of the string (-6+6( total number of characters)= 0: this is method can be used to calculate negative number positioning)